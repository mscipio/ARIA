/**
 * The one authoritative list of what ARIA depends on. Setup, update, diagnostics, the CLI and the
 * management TUI all read this; nothing else declares dependencies.
 *
 * Ownership:
 *   external  installed and upgraded by the user (or a hosted service); ARIA only detects it and
 *             never changes it
 *   aria      installed by ARIA under ARIA_HOME (tools/<id>) or inside an ARIA release; setup,
 *             update, rollback and repair cover it
 *   either    reused if an existing compatible installation is found, otherwise ARIA can install
 *             its own copy under ARIA_HOME; an existing copy is never modified
 *
 * Integrations ARIA neither needs nor manages are not listed at all (CodeGraph: no ARIA 2 role uses
 * it). Engram was removed in alpha.5 by mistake and is back as a shared capability. Users can still configure any MCP server themselves; its tools are
 * unclassified, so coding roles ask before each use and read-only roles cannot see them.
 *
 * No secrets live here. MCP configuration written by ARIA contains executable paths and fixed
 * environment flags only; credentials stay in the user's own config or the server's own store.
 */

/**
 * required: ARIA cannot work without it. role: ARIA works, but the listed roles are not fully
 * ready without it (health reports it; other roles keep working). optional: off until enabled.
 */
export type Requirement = "required" | "role" | "optional";
export type Ownership = "external" | "aria" | "either";
export type Kind = "runtime" | "package" | "mcp" | "skill";

export interface Install {
  /** `npm-prefix`: `npm install <package>@<pin>` into tools/<id>-<stamp>. `python-venv`: venv in tools/<id>-<stamp> + pip `<package>==<pin>`. `release-deps`: `npm ci --omit=dev` from the release lockfile. */
  readonly method: "npm-prefix" | "python-venv" | "release-deps" | "skill-archive" | "github-binary";
  readonly package?: string;
  /** Exact version ARIA installs (reproducible); an upgrade of ARIA may move the pin. */
  readonly pin?: string;
  /** Executable inside the managed install, relative to tools/<id>. */
  readonly executable?: string;
  readonly network: true;
}

/**
 * A prebuilt executable from a GitHub release: one pinned asset per `<platform>-<arch>`, each
 * verified against its SHA-256 before anything is extracted (the values come from the release's own
 * checksums.txt, so they prove content, not publisher). Hosts without an asset get no managed copy.
 */
export interface BinaryPin {
  readonly version: string;
  readonly assets: Readonly<Record<string, { readonly url: string; readonly sha256: string; readonly member: string }>>;
}

/**
 * An OpenCode plugin file an integration needs next to its MCP entry. OpenCode 2.3.0 loads such a
 * plugin only from a `plugins/` directory (verified: a path in the `plugins` array is ignored), so
 * ARIA writes one file into the chosen scope's plugins directory and records it as ARIA-owned.
 * The content is generated by the integration's own executable, so it matches that version.
 */
export interface PluginFile {
  readonly file: string;
  /** Text that identifies a genuine copy (also one the user installed). */
  readonly markers: readonly string[];
  /** Arguments that make the executable write its OpenCode plugin under `<XDG_CONFIG_HOME>/opencode/plugins/<file>`, run in a throw-away HOME. */
  readonly generate: readonly string[];
}

/**
 * A skill ARIA installs from a pinned upstream archive into an OpenCode skills directory
 * (`<config root>/skills/<name>`), so OpenCode discovers it natively. Both artifacts are verified
 * against the SHA-256 pins before anything is written; the installed tree carries an ownership
 * marker with per-file hashes, and ARIA only ever updates, repairs or removes a tree it owns and
 * that is unmodified.
 */
export interface SkillPin {
  readonly name: string;
  readonly version: string;
  readonly commit: string;
  readonly archiveUrl: string;
  readonly archiveSha256: string;
  /** Directory inside the archive's top-level folder that holds the skill. */
  readonly sourcePrefix: string;
  /** Substrings the archive's root LICENSE must contain (licence identity check). */
  readonly licenseMarkers: readonly string[];
  /** Optional native helper, pinned per platform (`<platform>-<arch>`); other platforms get the skill without it. */
  readonly engine?: { readonly platform: string; readonly url: string; readonly sha256: string; readonly relative: string };
}

export interface Dependency {
  readonly id: string;
  readonly name: string;
  readonly purpose: string;
  readonly kind: Kind;
  readonly requirement: Requirement;
  /** ARIA roles that use it (used for role-readiness reporting). */
  readonly roles?: readonly string[];
  /** Optional integrations are off until the user enables them. */
  readonly defaultEnabled: boolean;
  readonly ownership: Ownership;
  readonly platforms?: readonly NodeJS.Platform[];
  /** How to find an existing copy. */
  readonly executable?: string;
  readonly searchDirs?: () => string[];
  /** Arguments that print a version, and the compatible range. */
  readonly versionArgs?: readonly string[];
  readonly range?: string;
  readonly install?: Install;
  /** For `skill-archive` installs. */
  readonly skill?: SkillPin;
  /** For `github-binary` installs. */
  readonly binary?: BinaryPin;
  /** Plugin file registered with the MCP entry. */
  readonly plugin?: PluginFile;
  /** How the user installs an external dependency (shown, never executed by ARIA). */
  readonly installHint?: string;
  /** For MCP integrations: the OpenCode `mcp.servers.<name>` entry ARIA writes when enabled. */
  readonly mcp?: {
    readonly server: string;
    /** undefined: user-managed integration; ARIA detects it but never writes its entry. */
    readonly config?: (executable: string | undefined) => Record<string, unknown>;
    /** A tool inventory check is possible (local stdio server). */
    readonly probe: boolean;
    /** Tool names ARIA's role rules classify; the probe reports anything else as unclassified. */
    readonly classes?: { readonly read: readonly string[]; readonly mutate: readonly string[] };
    /** Operational readiness: a read-only tool call that needs the backing service (e.g. Zotero desktop). */
    readonly readyCall?: { readonly tool: string; readonly args: Record<string, unknown>; readonly needs: string };
    /** Remote server: readiness is an MCP `initialize` over HTTP (network). */
    readonly remoteUrl?: string;
  };
  /** Extra provisioning after install (Playwright browsers). */
  readonly provision?: { readonly what: string; readonly args: readonly string[]; readonly dir: string; readonly network: true };
  readonly upgrade: string;
  /** Network needed for its health check. */
  readonly healthNeedsNetwork?: boolean;
}

